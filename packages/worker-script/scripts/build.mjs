import { build } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { esbuildTwinGuard } from "../../../scripts/declaration-twin-guard.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, "..");
const SRC_ENTRY = resolve(PKG_ROOT, "src/index.ts");
const DIST_DIR = resolve(PKG_ROOT, "dist");
const BUNDLE_OUT = resolve(DIST_DIR, "worker-script.js");
const INDEX_OUT = resolve(DIST_DIR, "index.js");
const TYPES_OUT = resolve(DIST_DIR, "index.d.ts");
const BYTES_PER_KIB = 1024;

async function run() {
  await rm(DIST_DIR, { recursive: true, force: true });
  await mkdir(DIST_DIR, { recursive: true });

  const result = await build({
    entryPoints: [SRC_ENTRY],
    outfile: BUNDLE_OUT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "esnext",
    external: ["cloudflare:*", "node:*", "./__ks_worker_script.js"],
    minify: true,
    keepNames: true,
    sourcemap: false,
    logLevel: "warning",
    conditions: ["workerd", "worker", "browser"],
    resolveExtensions: [".ts", ".mjs", ".js", ".json"],
    plugins: [esbuildTwinGuard],
  });
  if (result.errors.length) {
    throw new Error(`esbuild reported ${result.errors.length} error(s); aborting`);
  }

  const bundled = await readFile(BUNDLE_OUT, "utf8");
  await writeFile(
    INDEX_OUT,
    "// AUTO-GENERATED by scripts/build.mjs. Do not edit by hand.\n" +
      "// Runtime module for a dedicated-worker loaded worker; the engine\n" +
      "// feeds it into env.LOADER.load(...) as mainModule `worker.js`.\n" +
      "export const WORKER_SCRIPT_SOURCE = " +
      JSON.stringify(bundled) +
      ";\n",
  );
  await writeFile(
    TYPES_OUT,
    "// AUTO-GENERATED by scripts/build.mjs. Do not edit by hand.\n" +
      "export declare const WORKER_SCRIPT_SOURCE: string;\n",
  );
  const kib = (bundled.length / BYTES_PER_KIB).toFixed(1);
  console.log(`[worker-script] bundled ${bundled.length} chars (${kib} KiB)`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
