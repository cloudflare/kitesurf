import { build } from "vite";
import { transform as esbuildTransform } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { materializeEditingImplementation } from "./editing-implementation.mjs";
import { rollupTwinGuard } from "../../../scripts/declaration-twin-guard.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, "..");
const SRC_ENTRY = resolve(PKG_ROOT, "src/index.ts");
const DIST_DIR = resolve(PKG_ROOT, "dist");
const BUNDLE_OUT = resolve(DIST_DIR, "dom-shim.js");
const INDEX_OUT = resolve(DIST_DIR, "index.js");
const TYPES_OUT = resolve(DIST_DIR, "index.d.ts");

const INTERNAL_STATE_RE = /(^|\/)internal-state\.js$/;

async function run() {
  await rm(DIST_DIR, { recursive: true, force: true });
  await mkdir(DIST_DIR, { recursive: true });

  await materializeEditingImplementation();

  await build({
    root: PKG_ROOT,
    configFile: false,
    logLevel: "warn",
    build: {
      lib: {
        entry: SRC_ENTRY,
        formats: ["es"],
        fileName: () => "dom-shim.js",
      },
      outDir: DIST_DIR,
      emptyOutDir: false,
      target: "esnext",
      minify: "esbuild",
      sourcemap: false,
      cssMinify: false,
      cssCodeSplit: false,
      reportCompressedSize: false,
      rollupOptions: {
        external: (id) => INTERNAL_STATE_RE.test(id),
        output: {
          paths: (id) => (INTERNAL_STATE_RE.test(id) ? "./internal-state.js" : id),
        },
        treeshake: true,
        plugins: [rollupTwinGuard],
      },
    },
    esbuild: {
      keepNames: true,
      legalComments: "none",
      minifyWhitespace: true,
      minifyIdentifiers: true,
      minifySyntax: true,
    },
  });

  {
    const raw = await readFile(BUNDLE_OUT, "utf8");
    const minified = await esbuildTransform(raw, {
      minify: true,
      keepNames: true,
      target: "esnext",
      format: "esm",
      legalComments: "none",
    });
    await writeFile(BUNDLE_OUT, minified.code);
  }

  const bundled = await readFile(BUNDLE_OUT, "utf8");

  const wrapper =
    "// AUTO-GENERATED by scripts/build.mjs. Do not edit by hand.\n" +
    "// The bundled JS source is the runtime that lives inside the\n" +
    "// per-page Worker Loader sandbox; the engine worker feeds it\n" +
    "// into env.LOADER.load(...) as a sibling module named `dom-shim.js`.\n" +
    "export const DOM_SHIM_SOURCE = " +
    JSON.stringify(bundled) +
    ";\n";
  await writeFile(INDEX_OUT, wrapper);

  const types =
    "// AUTO-GENERATED by scripts/build.mjs. Do not edit by hand.\n" +
    "export declare const DOM_SHIM_SOURCE: string;\n";
  await writeFile(TYPES_OUT, types);

  const kib = (bundled.length / 1024).toFixed(1);
  console.log(`[dom-shim] bundled ${bundled.length} chars (${kib} KiB)`);
  console.log(`[dom-shim]   ${BUNDLE_OUT}`);
  console.log(`[dom-shim]   ${INDEX_OUT}`);
  console.log(`[dom-shim]   ${TYPES_OUT}`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
