// Cut the public e2e suite into contiguous path ranges from per-file durations.

import { globSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { isMain } from "./wpt-shared.mjs";

const ROOT = resolve(import.meta.dirname, "..");
const ENGINE_DIR = resolve(ROOT, "packages/engine");
const USAGE = `usage: node scripts/e2e-shards.mjs --durations <file>... [--target-s <s>] [--workers <n>] [--out <file>]
A durations file is a vitest JSON report or a { "test/e2e/<file>": ms } map. Defaults: 60 s, 3
workers, tests/e2e/shards.bzl.`;

function parseArgs(argv) {
  const options = {
    durations: [],
    targetMs: 60_000,
    workers: 3,
    out: resolve(ROOT, "tests/e2e/shards.bzl"),
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    switch (arg) {
      case "--durations":
        options.durations.push(resolve(argv[++i]));
        break;
      case "--target-s":
        options.targetMs = Number(argv[++i]) * 1000;
        break;
      case "--workers":
        options.workers = parseInt(argv[++i], 10);
        break;
      case "--out":
        options.out = resolve(argv[++i]);
        break;
      default:
        console.error(USAGE);
        process.exit(2);
    }
  }
  if (!options.durations.length) {
    console.error(USAGE);
    process.exit(2);
  }
  return options;
}

function readDurations(files) {
  const durations = {};
  const keep = (file, ms) => (durations[file] = Math.max(durations[file] ?? 0, ms));
  for (const file of files) {
    const data = JSON.parse(readFileSync(file, "utf8"));
    if (Array.isArray(data.testResults)) {
      for (const result of data.testResults) {
        keep(
          result.name.slice(result.name.lastIndexOf("/test/e2e/") + 1),
          result.endTime - result.startTime,
        );
      }
    } else {
      for (const [name, ms] of Object.entries(data)) keep(name, ms);
    }
  }
  return durations;
}

function medianDuration(known) {
  return known.length ? known[Math.floor(known.length / 2)] : 1000;
}

function shardFits(current, duration, targetMs, workers) {
  return current && Math.max(current.max, duration, (current.sum + duration) / workers) <= targetMs;
}

/** @param {string[]} files @param {Record<string, number>} durations @param {number} targetMs @param {number} workers @returns {{start: string, files: string[], sum: number, max: number}[]} */
export function cut(files, durations, targetMs, workers) {
  const known = files
    .map((file) => durations[file])
    .filter((ms) => ms !== undefined)
    .sort((a, b) => a - b);
  const median = medianDuration(known);
  const shards = [];
  let current = null;
  for (const file of files) {
    const ms = durations[file] ?? median;
    if (!shardFits(current, ms, targetMs, workers))
      shards.push((current = { start: file, files: [], sum: 0, max: 0 }));
    current.files.push(file);
    current.sum += ms;
    current.max = Math.max(current.max, ms);
  }
  return shards;
}

function main(options) {
  const files = globSync("test/e2e/**/*.e2e.test.ts", { cwd: ENGINE_DIR })
    .map((file) => file.replaceAll("\\", "/"))
    .sort();
  const shards = cut(files, readDurations(options.durations), options.targetMs, options.workers);
  const starts = shards.map((shard, index) => (index === 0 ? "" : shard.start));
  const lines = [
    '"""Generated by `node scripts/e2e-shards.mjs` from measured durations; regenerate, do not hand-edit.',
    `Each entry starts a shard's range of sorted test paths."""`,
    "",
    "E2E_SHARD_STARTS = [",
    ...starts.map((start) => `    ${JSON.stringify(start)},`),
    "]",
    "",
  ];
  writeFileSync(options.out, lines.join("\n"));
  for (const [index, shard] of shards.entries()) {
    const wall = Math.max(shard.max, shard.sum / options.workers) / 1000;
    console.log(
      `shard_${String(index + 1).padStart(2, "0")}: ${shard.files.length} files, ~${wall.toFixed(0)}s  ${shard.start}`,
    );
  }
  console.log(
    `[e2e-shards] ${files.length} files → ${shards.length} shards in ${relative(ROOT, options.out)}`,
  );
}

if (isMain(import.meta.url)) main(parseArgs(process.argv.slice(2)));
